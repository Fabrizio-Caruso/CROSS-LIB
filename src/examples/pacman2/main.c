 /* ---- main ---- */
 int main(void)
 {
     uint8_t inp;
     uint8_t i;
 
     _XL_INIT_GRAPHICS();
     _XL_INIT_INPUT();
     _XL_INIT_SOUND();
 
     while (1) {
         /* Title screen */
         state = 0;
         _XL_CLEAR_SCREEN();
         _XL_SET_TEXT_COLOR(_XL_YELLOW);
         _XL_PRINT(2, 2, "PACMAN");
         _XL_SET_TEXT_COLOR(_XL_WHITE);
         _XL_PRINT(0, 5, "42 LEVELS");
         _XL_PRINT(0, 7, "PRESS ANY KEY");
         _XL_PRINT(0, 9, "ARROWS TO MOVE");
         _XL_PRINT(0, 10, "FIRE TO SHOOT");
         _XL_WAIT_FOR_INPUT();
 
         /* Start game */
         score = 0;
         lives = 3;
         curlevel = 0;
         setup_level(0);
         render_level();
 
         while (1) {
             /* Game over check */
             if (lives < 1) {
                 _XL_CLEAR_SCREEN();
                 _XL_SET_TEXT_COLOR(_XL_RED);
                 _XL_PRINT(2, 4, "GAME OVER");
                 _XL_SET_TEXT_COLOR(_XL_WHITE);
                 _XL_PRINT(0, 7, "PRESS ANY KEY");
                 _XL_PING_SOUND();
                 _XL_WAIT_FOR_INPUT();
                 break;
             }
 
             /* Level complete check */
             if (pellets < 1) {
                 _XL_SET_TEXT_COLOR(_XL_CYAN);
                 _XL_PRINT(1, 4, "LEVEL CLEAR!");
                 _XL_SET_TEXT_COLOR(_XL_WHITE);
                 _XL_PRINT(1, 6, "SCORE:");
                 _XL_PRINTD(1, 7, 1, score);
                 _XL_SLOW_DOWN(20 * _XL_SLOW_DOWN_FACTOR);
                 curlevel++;
                 if (curlevel >= NUM_LEVELS) {
                     /* All levels done, restart from 0 */
                     score = 0;
                     curlevel = 0;
                     lives = 3;
                 }
                 setup_level(curlevel);
                 render_level();
                 continue;
             }
 
             /* Gun countdown */
             if (gun > 0) {
                 gun--;
             }
 
             /* Input */
             inp = _XL_INPUT();
             if (_XL_UP(inp))
                 pdir = 0;
             else if (_XL_RIGHT(inp))
                 pdir = 1;
             else if (_XL_DOWN(inp))
                 pdir = 2;
             else if (_XL_LEFT(inp))
                 pdir = 3;
 
             /* Fire bullet if gun active */
             if (_XL_FIRE(inp) && gun > 0 && nbullets < MAX_BULLETS) {
                 i = 0;
                 while (i < MAX_BULLETS) {
                     if (!balive[i])
                         break;
                     i++;
                 }
                 if (i < MAX_BULLETS) {
                     balive[i] = 1;
                     bxs[i] = px;
                     bys[i] = py;
                     bdirs[i] = pdir;
                     nbullets++;
                     _XL_SHOOT_SOUND();
                 }
             }
 
             /* Move player */
             move_player();
 
             /* Move enemies */
             move_enemies();
 
             /* Move bullets */
             move_bullets();
 
             /* Collisions */
             do_collisions();
 
             /* Check level complete */
             check_level_complete();
 
             /* Short delay */
             _XL_SLOW_DOWN(_XL_SLOW_DOWN_FACTOR * 5);
         }
     }
     return 0;
 }
 
 /* ---- setup level ---- */
 void setup_level(uint8_t l)
 {
     uint8_t i, j;
     uint8_t cnt;
 
     cnt = 0;
     for (i = 0; i < GRID_H; i++) {
         for (j = 0; j < GRID_W; j++) {
             g[j][i] = lvl[l][i * GRID_W + j];
             if (g[j][i] == LV_PELLET)
                 cnt++;
         }
     }
     pellets = cnt;
 
     px = START_PX;
     py = START_PY;
     pdir = 1;
     g[px][py] = LV_EMPTY;
 
     ex[0] = START_EX0; ey[0] = START_EY0; edir[0] = 1; alive[0] = 1;
     ex[1] = START_EX1; ey[1] = START_EY1; edir[1] = 3; alive[1] = 1;
     ex[2] = START_EX2; ey[2] = START_EY2; edir[2] = 1; alive[2] = 1;
     ex[3] = START_EX3; ey[3] = START_EY3; edir[3] = 3; alive[3] = 1;
     for (i = 0; i < 4; i++) {
         g[ex[i]][ey[i]] = LV_EMPTY;
     }
 
     for (i = 0; i < MAX_BULLETS; i++) {
         balive[i] = 0;
     }
     nbullets = 0;
     gun = 0;
 }
 
 /* ---- render full level (initial draw) ---- */
 void render_level(void)
 {
     uint8_t i, j;
 
     /* Draw walls */
     for (i = 0; i < GRID_H; i++) {
         for (j = 0; j < GRID_W; j++) {
             if (g[j][i] == LV_WALL) {
                 _XL_DRAW(j, i + GYOFF, _TILE_1, _XL_BLUE);
             } else if (g[j][i] == LV_PELLET) {
                 _XL_DRAW(j, i + GYOFF, _TILE_2, _XL_YELLOW);
             } else if (g[j][i] == LV_GUN) {
                 _XL_DRAW(j, i + GYOFF, _TILE_6, _XL_CYAN);
             }
         }
     }
 
     /* Draw player */
     _XL_DRAW(px, py + GYOFF, _TILE_3, _XL_YELLOW);
 
     /* Draw enemies */
     for (i = 0; i < NUM_ENEMIES; i++) {
         if (alive[i]) {
             _XL_DRAW(ex[i], ey[i] + GYOFF, _TILE_4, _XL_RED);
         }
     }
 
     /* HUD */
     _XL_SET_TEXT_COLOR(_XL_WHITE);
     _XL_PRINT(0, 0, "SCORE:");
     _XL_PRINTD(5, 0, 1, score);
     _XL_PRINT(10, 0, "LV:");
     _XL_PRINTD(13, 0, 1, curlevel);
     _XL_PRINT(0, 1, "LIVES:");
     _XL_PRINTD(5, 1, 1, lives);
 }
 
 /* ---- move player one step ---- */
 void move_player(void)
 {
     uint8_t nx, ny;
     uint8_t oldx, oldy;
     short tx, ty;
 
     oldx = px;
     oldy = py;
     tx = (short)px + dx4[pdir];
     ty = (short)py + dy4[pdir];
 
     if (tx < 0 || ty < 0 || tx >= (short)GRID_W || ty >= (short)GRID_H)
         return;
     nx = (uint8_t)tx;
     ny = (uint8_t)ty;
 
     if (g[nx][ny] == LV_WALL)
         return;
 
     /* Remove player from old position */
     _XL_DELETE(oldx, oldy + GYOFF);
 
     /* Check pellet */
     if (g[nx][ny] == LV_PELLET) {
         g[nx][ny] = LV_EMPTY;
         pellets--;
         score += 10;
         _XL_SET_TEXT_COLOR(_XL_WHITE);
         _XL_PRINTD(5, 0, 1, score);
     } else if (g[nx][ny] == LV_GUN) {
         g[nx][ny] = LV_EMPTY;
         gun = GUN_TICKS;
         _XL_PING_SOUND();
     } else {
         g[nx][ny] = LV_EMPTY;
     }
 
     px = nx;
     py = ny;
     _XL_DRAW(px, py + GYOFF, _TILE_3, _XL_YELLOW);
 }
 
 /* ---- move all enemies ---- */
 void move_enemies(void)
 {
     uint8_t i;
     for (i = 0; i < NUM_ENEMIES; i++) {
         if (!alive[i])
             continue;
         /* one enemy step */
         {
             uint8_t nx, ny, nd;
             short tx, ty;
             uint8_t best, bd;
             uint8_t d;
             uint8_t cx, cy;
             uint8_t opts[4];
             uint8_t nopts;
             uint8_t k;
 
             cx = ex[i];
             cy = ey[i];
 
             /* try current direction */
             tx = (short)cx + dx4[edir[i]];
             ty = (short)cy + dy4[edir[i]];
             if (tx >= 0 && ty >= 0 && tx < (short)GRID_W && ty < (short)GRID_H) {
                 if (g[(uint8_t)tx][(uint8_t)ty] != LV_WALL) {
                     nd = edir[i];
                 } else {
                     nd = 255;
                 }
             } else {
                 nd = 255;
             }
 
             if (nd != 255) {
                 /* continue */
                 {
                     uint8_t ox, oy;
                     ox = cx;
                     oy = cy;
                     _XL_DELETE(ox, oy + GYOFF);
                     if (g[ox][oy] == LV_PELLET)
                         _XL_DRAW(ox, oy + GYOFF, _TILE_2, _XL_YELLOW);
                     else if (g[ox][oy] == LV_GUN)
                         _XL_DRAW(ox, oy + GYOFF, _TILE_6, _XL_CYAN);
 
                     ex[i] = (uint8_t)tx;
                     ey[i] = (uint8_t)ty;
                     g[cx][cy] = LV_EMPTY;
                     g[ex[i]][ey[i]] = LV_EMPTY;
                     _XL_DRAW(ex[i], ey[i] + GYOFF, _TILE_4, _XL_RED);
                 }
             } else {
                 /* pick new direction */
                 nopts = 0;
                 for (k = 0; k < 4; k++) {
                     short vx = (short)cx + dx4[k];
                     short vy = (short)cy + dy4[k];
                     if (vx >= 0 && vy >= 0 && vx < (short)GRID_W && vy < (short)GRID_H) {
                         if (g[(uint8_t)vx][(uint8_t)vy] != LV_WALL) {
                             opts[nopts] = k;
                             nopts++;
                         }
                     }
                 }
                 if (nopts < 1)
                     continue;
 
                 /* greedy toward player 70%, random 30% */
                 best = opts[0];
                 bd = 255;
                 for (k = 0; k < nopts; k++) {
                     d = (uint8_t)(opts[k] == 0 ? (cy - py) : 0);
                     if (opts[k] == 0) d = (cy > py) ? (uint8_t)(cy - py) : (uint8_t)(py - cy);
                     if (opts[k] == 2) d = (cy < py) ? (uint8_t)(py - cy) : (uint8_t)(cy - py);
                     if (opts[k] == 1) d = (cx > px) ? (uint8_t)(cx - px) : (uint8_t)(px - cx);
                     if (opts[k] == 3) d = (cx < px) ? (uint8_t)(px - cx) : (uint8_t)(cx - cx);
                     if (opts[k] == 1) d = (px > cx) ? (uint8_t)(px - cx) : (uint8_t)(cx - px);
                     if (opts[k] == 3) d = (cx > px) ? (uint8_t)(cx - px) : (uint8_t)(px - cx);
                     if (d < bd) {
                         bd = d;
                         best = opts[k];
                     }
                 }
                 /* random chance */
                 {
                     uint16_t r = _XL_RAND();
                     if (r % 10 < 3) {
                         best = opts[r % nopts];
                     }
                 }
 
                 nd = best;
                 tx = (short)cx + dx4[nd];
                 ty = (short)cy + dy4[nd];
                 edir[i] = nd;
 
                 {
                     uint8_t ox, oy;
                     ox = cx;
                     oy = cy;
                     _XL_DELETE(ox, oy + GYOFF);
                     if (g[ox][oy] == LV_PELLET)
                         _XL_DRAW(ox, oy + GYOFF, _TILE_2, _XL_YELLOW);
                     else if (g[ox][oy] == LV_GUN)
                         _XL_DRAW(ox, oy + GYOFF, _TILE_6, _XL_CYAN);
 
                     ex[i] = (uint8_t)tx;
                     ey[i] = (uint8_t)ty;
                     g[cx][cy] = LV_EMPTY;
                     g[ex[i]][ey[i]] = LV_EMPTY;
                     _XL_DRAW(ex[i], ey[i] + GYOFF, _TILE_4, _XL_RED);
                 }
             }
         }
     }
 }
 
 /* ---- move bullets ---- */
 void move_bullets(void)
 {
     uint8_t i;
     uint8_t nx, ny;
     short tx, ty;
 
     for (i = 0; i < MAX_BULLETS; i++) {
         if (!balive[i])
             continue;
 
         tx = (short)bxs[i] + dx4[bdirs[i]];
         ty = (short)bys[i] + dy4[bdirs[i]];
 
         if (tx < 0 || ty < 0 || tx >= (short)GRID_W || ty >= (short)GRID_H) {
             _XL_DELETE(bxs[i], bys[i] + GYOFF);
             balive[i] = 0;
             continue;
         }
         nx = (uint8_t)tx;
         ny = (uint8_t)ty;
 
         if (g[nx][ny] == LV_WALL) {
             _XL_DELETE(bxs[i], bys[i] + GYOFF);
             balive[i] = 0;
             continue;
         }
 
         /* move bullet */
         _XL_DELETE(bxs[i], bys[i] + GYOFF);
         bxs[i] = nx;
         bys[i] = ny;
         _XL_DRAW(bxs[i], bys[i] + GYOFF, _TILE_5, _XL_CYAN);
     }
 }
 
 /* ---- collision detection ---- */
 void do_collisions(void)
 {
     uint8_t i;
 
     /* bullets hit enemies */
     for (i = 0; i < MAX_BULLETS; i++) {
         if (!balive[i])
             continue;
         {
             uint8_t j;
             for (j = 0; j < NUM_ENEMIES; j++) {
                 if (!alive[j])
                     continue;
                 if (bxs[i] == ex[j] && bys[i] == ey[j]) {
                     /* enemy killed */
                     _XL_DELETE(ex[j], ey[j] + GYOFF);
                     g[ex[j]][ey[j]] = LV_EMPTY;
                     alive[j] = 0;
                     balive[i] = 0;
                     score += 100;
                     _XL_SET_TEXT_COLOR(_XL_WHITE);
                     _XL_PRINTD(5, 0, 1, score);
                     _XL_EXPLOSION_SOUND();
                 }
             }
         }
     }
 
     /* player hit by enemy (if not gun active) */
     if (gun < 1) {
         for (i = 0; i < NUM_ENEMIES; i++) {
             if (!alive[i])
                 continue;
             if (px == ex[i] && py == ey[i]) {
                 lives--;
                 _XL_SET_TEXT_COLOR(_XL_WHITE);
                 _XL_PRINTD(5, 1, 1, lives);
                 _XL_ZAP_SOUND();
                 /* restart current level */
                 setup_level(curlevel);
                 return;
             }
         }
     }
 }
 
 /* ---- check if level is complete ---- */
 void check_level_complete(void)
 {
     uint8_t i;
     uint8_t any;
 
     any = 0;
     for (i = 0; i < NUM_ENEMIES; i++) {
         if (alive[i])
             any = 1;
     }
 
     /* all pellets collected OR all enemies killed */
     if ((pellets < 1) || (any == 0)) {
         if (pellets > 0) {
             /* bonus for killing all enemies */
             score += 500;
             _XL_SET_TEXT_COLOR(_XL_WHITE);
             _XL_PRINTD(5, 0, 1, score);
         }
         pellets = 0;
         _XL_TICK_SOUND();
     }
 }
 
