static void load_level(uint8_t lvl)
{
    uint8_t x, y;
    const char *row;
    enemy_count = 0;
    bullet_count = 0;
    px = 1; py = 1;
    has_gun = 0; invincible = 0; full_visible = 0;
    last_dx = 1; last_dy = 0;

    for (y = 0; y < MAP_H; y++) {
        row = level_data[lvl][y];
        for (x = 0; x < MAP_W; x++) {
            item_map[x][y] = 0;
            switch (row[x]) {
                case '#': map_data[x][y] = 1; break;
                case 'E': map_data[x][y] = 2; break;
                default:  map_data[x][y] = 0; break;
            }
            if (row[x] == 'G') item_map[x][y] = 1;
            else if (row[x] == 'I') item_map[x][y] = 2;
            else if (row[x] == 'V') item_map[x][y] = 3;
            else if (row[x] == 'e' && enemy_count < MAX_ENEMIES) {
                ex[enemy_count] = x;
                ey[enemy_count] = y;
                enemy_count++;
            }
        }
    }
}

static void clear_prev(void)
{
    uint8_t x, y;
    for (y = 0; y < MAP_H; y++)
        for (x = 0; x < MAP_W; x++) {
            prev_tile[x][y] = 255;
            prev_color[x][y] = 255;
        }
}

static uint8_t is_visible(uint8_t cx, uint8_t cy)
{
    short dx, dy;
    if (full_visible) return 1;
    dx = (short)cx - (short)px;
    dy = (short)cy - (short)py;
    if (dx < 0) dx = -dx;
    if (dy < 0) dy = -dy;
    return ((uint8_t)(dx + dy) <= VIS_R);
}

static uint8_t is_wall(uint8_t x, uint8_t y)
{
    return map_data[x][y] == 1;
}

static void move_enemies(void)
{
    uint8_t i;
    short dx, dy;
    for (i = 0; i < enemy_count; i++) {
        if ((short)(px - ex[i]) > 0) dx = 1;
        else if ((short)(px - ex[i]) < 0) dx = -1;
        else dx = 0;
        if ((short)(py - ey[i]) > 0) dy = 1;
        else if ((short)(py - ey[i]) < 0) dy = -1;
        else dy = 0;
        if (dx != 0 && !is_wall((uint8_t)(ex[i]+dx), ey[i])) {
            ex[i] = (uint8_t)(ex[i]+dx);
        } else if (dy != 0 && !is_wall(ex[i], (uint8_t)(ey[i]+dy))) {
            ey[i] = (uint8_t)(ey[i]+dy);
        }
    }
}

static void move_bullets(void)
{
    uint8_t i, j;
    for (i = 0; i < bullet_count; i++) {
        bx[i] = (uint8_t)(bx[i] + bdx[i]);
        by[i] = (uint8_t)(by[i] + bdy[i]);
        if (is_wall(bx[i], by[i])) {
            for (j = i; j < bullet_count - 1; j++) {
                bx[j]=bx[j+1]; by[j]=by[j+1];
                bdx[j]=bdx[j+1]; bdy[j]=bdy[j+1];
            }
            bullet_count--;
            i--;
        } else {
            for (j = 0; j < enemy_count; j++) {
                if (bx[i]==ex[j] && by[i]==ey[j]) {
                    for (; j<enemy_count-1; j++) { ex[j]=ex[j+1]; ey[j]=ey[j+1]; }
                    enemy_count--;
                    score += 50;
                    _XL_PING_SOUND();
                    break;
                }
            }
        }
    }
}

static void check_collisions(void)
{
    uint8_t i;
    for (i = 0; i < enemy_count; i++) {
        if (px==ex[i] && py==ey[i]) {
            if (!invincible) {
                lives--;
                _XL_EXPLOSION_SOUND();
                if (lives > 0) { px=1; py=1; }
            }
        }
    }
}

static void check_items(void)
{
    if (item_map[px][py]==1 && !has_gun) {
        has_gun=1; item_map[px][py]=0;
        _XL_TICK_SOUND();
    } else if (item_map[px][py]==2) {
        invincible=INVINCIBILITY_DURATION; item_map[px][py]=0;
        _XL_TOCK_SOUND();
    } else if (item_map[px][py]==3 && !full_visible) {
        full_visible=1; item_map[px][py]=0;
        _XL_PING_SOUND();
    }
}

static void render(void)
{
    uint8_t x, y, sx, sy;
    uint8_t tile, color;
    uint8_t i;
    for (y = 0; y < MAP_H; y++) {
        for (x = 0; x < MAP_W; x++) {
            sx = OX + x;
            sy = OY + y;
            if (!is_visible(x, y)) {
                tile = _TILE_1;
                color = _XL_BLUE;
            } else {
                tile = 0; color = 0;
                for (i = 0; i < bullet_count; i++) {
                    if (bx[i]==x && by[i]==y) { tile=_TILE_2; color=_XL_YELLOW; break; }
                }
                if (!tile) {
                    for (i = 0; i < enemy_count; i++) {
                        if (ex[i]==x && ey[i]==y) { tile=_TILE_7; color=_XL_RED; break; }
                    }
                }
                if (!tile && item_map[x][y]) {
                    if (item_map[x][y]==1) { tile=_TILE_9; color=_XL_CYAN; }
                    else if (item_map[x][y]==2) { tile=_TILE_11; color=_XL_MAGENTA; }
                    else { tile=_TILE_4; color=_XL_WHITE; }
                }
                if (!tile && px==x && py==y) {
                    tile = _TILE_5;
                    color = invincible ? _XL_YELLOW : _XL_GREEN;
                }
                if (!tile) {
                    if (map_data[x][y]==1) { tile=_TILE_1; color=_XL_WHITE; }
                    else if (map_data[x][y]==2) { tile=_TILE_3; color=_XL_YELLOW; }
                    else { tile=_TILE_0; color=_XL_BLUE; }
                }
            }
            if (tile != prev_tile[x][y] || color != prev_color[x][y]) {
                _XL_DRAW(sx, sy, tile, color);
                prev_tile[x][y] = tile;
                prev_color[x][y] = color;
            }
        }
    }
}

static void render_ui(void)
{
    _XL_SET_TEXT_COLOR(_XL_WHITE);
    _XL_PRINT(2, 1, "SCORE");
    _XL_PRINTD(OX + MAP_W - 4, 1, 1, score);
    _XL_SET_TEXT_COLOR(_XL_GREEN);
    _XL_PRINT(2, 3, "LIVES");
    _XL_PRINTD(OX + MAP_W - 4, 3, 1, lives);
    _XL_SET_TEXT_COLOR(_XL_YELLOW);
    _XL_PRINT(2, 5, "LEVEL");
    _XL_PRINTD(OX + MAP_W - 6, 5, 1, (uint16_t)current_level + 1);
    if (has_gun) {
        _XL_SET_TEXT_COLOR(_XL_CYAN);
        _XL_PRINT(2, 7, "GUN: YES");
    } else {
        _XL_SET_TEXT_COLOR(_XL_BLUE);
        _XL_PRINT(2, 7, "GUN: NO ");
    }
    if (full_visible) {
        _XL_SET_TEXT_COLOR(_XL_WHITE);
        _XL_PRINT(OX + MAP_W - 8, 7, "FULL VIEW");
    } else if (invincible) {
        _XL_SET_TEXT_COLOR(_XL_MAGENTA);
        _XL_PRINT(OX + MAP_W - 8, 7, "INVINCIBLE");
    } else {
        _XL_SET_TEXT_COLOR(_XL_BLUE);
        _XL_PRINT(OX + MAP_W - 8, 7, "          ");
    }
}

int main(void)
{
    uint8_t input;
    uint8_t frame_count;
    uint8_t game_over;
    uint8_t level_complete;

    _XL_INIT_GRAPHICS();
    _XL_INIT_INPUT();
    _XL_INIT_SOUND();

    score = 0;
    lives = 3;
    current_level = 0;

    while (1) {
        load_level(current_level);
        clear_prev();
        frame_count = 0;
        game_over = 0;
        level_complete = 0;

        render();
        render_ui();

        while (!game_over && !level_complete) {
            input = _XL_INPUT();

            if (_XL_LEFT(input)) {
                last_dx=-1; last_dy=0;
                if (px > 0 && !is_wall(px-1, py)) px--;
            } else if (_XL_RIGHT(input)) {
                last_dx=1; last_dy=0;
                if ((uint8_t)(px+1) < MAP_W && !is_wall(px+1, py)) px++;
            } else if (_XL_UP(input)) {
                last_dx=0; last_dy=-1;
                if (py > 0 && !is_wall(px, py-1)) py--;
            } else if (_XL_DOWN(input)) {
                last_dx=0; last_dy=1;
                if ((uint8_t)(py+1) < MAP_H && !is_wall(px, py+1)) py++;
            }

            if (has_gun && _XL_FIRE(input) && bullet_count < MAX_BULLETS) {
                bx[bullet_count] = px;
                by[bullet_count] = py;
                bdx[bullet_count] = last_dx;
                bdy[bullet_count] = last_dy;
                bullet_count++;
                _XL_SHOOT_SOUND();
            }

            move_bullets();

            frame_count++;
            if (frame_count >= ENEMY_INTERVAL) {
                frame_count = 0;
                move_enemies();
            }

            if (invincible > 0) invincible--;

            check_collisions();
            check_items();

            if (map_data[px][py] == 2) {
                level_complete = 1;
                score += 100;
                _XL_ZAP_SOUND();
            }
            if (lives == 0) {
                game_over = 1;
                _XL_EXPLOSION_SOUND();
            }

            render();
            render_ui();
            _XL_SLOW_DOWN(_XL_SLOW_DOWN_FACTOR);
        }

        if (game_over) {
            _XL_SET_TEXT_COLOR(_XL_WHITE);
            _XL_PRINT((XSize-20)/2, YSize/2, "GAME OVER");
            _XL_WAIT_FOR_INPUT();
            score = 0;
            lives = 3;
            current_level = 0;
        } else {
            if (current_level < NUM_LEVELS - 1) {
                current_level++;
            } else {
                _XL_SET_TEXT_COLOR(_XL_YELLOW);
                _XL_PRINT((XSize-20)/2, YSize/2, "YOU WIN!");
                _XL_WAIT_FOR_INPUT();
                score = 0;
                lives = 3;
                current_level = 0;
            }
        }
    }

    return 0;
}
