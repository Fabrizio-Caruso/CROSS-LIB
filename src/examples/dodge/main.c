/* DODGE THE RAIN - Enhanced Edition
   Generated by QWEN 3.8 27B Q2
   Features: bullets, bonus items, invincibility,
   widening drops, ramping difficulty, scoring.
*/

#include "cross_lib.h"

/* ──────────── Constants ──────────── */

#define MAX_DROPS        20
#define MAX_BULLETS       8
#define MAX_ITEMS         4
#define MAX_LIVES         3
#define BASE_SPAWN        4
#define BULLET_START_AMMO  5
#define ITEM_EVERY         18
#define INVINC_FRAMES     160
#define DROP_SCORE         50
#define BONUS_SCORE       100
#define INVINC_SCORE      200

#define PLAYER_Y          ((YSize) - 2)

/* ──────────── Tile / Colour IDs ──── */

#define T_DROP          _TILE_5
#define T_WIDE_DROP     _TILE_10
#define T_BULLET        _TILE_25
#define T_BONUS         _TILE_15
#define T_INVINC        _TILE_20
#define T_PLAYER        _TILE_0

/* ──────────── Types ──────────────── */

typedef struct {
    uint8_t active;
    uint8_t x;
    uint8_t y;
    uint8_t wide;      /* 1 = normal, 2 = wide (occupies x and x+1) */
} Drop;

typedef struct {
    uint8_t active;
    uint8_t x;
    uint8_t y;
} Bullet;

typedef struct {
    uint8_t active;
    uint8_t x;
    uint8_t y;
    uint8_t kind;      /* 0 = bonus coin, 1 = invincibility star */
} Item;

/* ──────────── Game state ─────────── */

static Drop    drops[MAX_DROPS];
static Bullet  bullets[MAX_BULLETS];
static Item    items[MAX_ITEMS];
static uint8_t player_x;
static uint16_t score;
static uint8_t lives;
static uint8_t ammo;
static uint8_t spawn_timer;
static uint8_t item_timer;
static uint16_t invinc_timer;
static uint8_t difficulty;
static uint8_t frame_counter;

/* ═══════════ Helpers ═══════════ */

void reset_drops(void)
{
    uint8_t i;
    for (i = 0; i < MAX_DROPS; i++) drops[i].active = 0;
}

void reset_bullets(void)
{
    uint8_t i;
    for (i = 0; i < MAX_BULLETS; i++) bullets[i].active = 0;
}

void reset_items(void)
{
    uint8_t i;
    for (i = 0; i < MAX_ITEMS; i++) items[i].active = 0;
}

uint8_t find_drop_slot(void)
{
    uint8_t i;
    for (i = 0; i < MAX_DROPS; i++) {
        if (!drops[i].active) return i;
    }
    return MAX_DROPS;
}

uint8_t find_bullet_slot(void)
{
    uint8_t i;
    for (i = 0; i < MAX_BULLETS; i++) {
        if (!bullets[i].active) return i;
    }
    return MAX_BULLETS;
}

uint8_t find_item_slot(void)
{
    uint8_t i;
    for (i = 0; i < MAX_ITEMS; i++) {
        if (!items[i].active) return i;
    }
    return MAX_ITEMS;
}

/* ═══════════ Spawning ═══════════ */

void spawn_drop(void)
{
    uint8_t slot;
    uint8_t min_x;
    uint8_t max_x;
    uint8_t wide;
    uint16_t rand_val;

    slot = find_drop_slot();
    if (slot == MAX_DROPS) return;

    rand_val = _XL_RAND();
    wide = 1;
    if (difficulty > 3 && (rand_val % 5 == 0)) wide = 2;

    min_x = XSize / 5;
    if (wide == 2) {
        max_x = XSize - 1 - XSize / 5;
    } else {
        max_x = XSize - 1 - XSize / 5;
    }
    drops[slot].active = 1;
    drops[slot].x      = min_x + (uint8_t)(rand_val % (max_x - min_x));
    drops[slot].y      = 1;
    drops[slot].wide   = wide;
}

void spawn_item(void)
{
    uint8_t slot;
    uint16_t rand_val;
    uint8_t kind;

    slot = find_item_slot();
    if (slot == MAX_ITEMS) return;

    rand_val = _XL_RAND();
    kind = (rand_val % 4 == 0) ? 1 : 0;  /* 25% invinc, 75% bonus */

    items[slot].active = 1;
    items[slot].x      = (uint8_t)(XSize / 5 + rand_val % (XSize - 2 * (XSize / 5)));
    items[slot].y      = 1;
    items[slot].kind   = kind;
}

void fire_bullet(void)
{
    uint8_t slot;
    // uint8_t bx;

    if (ammo == 0) return;
    slot = find_bullet_slot();
    if (slot == MAX_BULLETS) return;

    ammo--;
    bullets[slot].active = 1;
    bullets[slot].x       = player_x;
    bullets[slot].y       = PLAYER_Y - 1;
    // bx = player_x;
    _XL_SHOOT_SOUND();
}

/* ═══════════ HUD ═══════════ */

void draw_hud(void)
{
    uint8_t i;
    uint8_t hx;

    /* lives (row 0, left) */
    for (i = 0; i < MAX_LIVES; i++) {
        hx = (uint8_t)(i + 1);
        if (i < lives) {
            _XL_DRAW(hx, 0, T_PLAYER, _XL_CYAN);
        } else {
            _XL_DELETE(hx, 0);
        }
    }

    /* score (row 0, right) */
    _XL_SET_TEXT_COLOR(_XL_WHITE);
    _XL_PRINTD(XSize - 6, 0, 5, score);

    /* bullets (row 1, left) */
    _XL_SET_TEXT_COLOR(_XL_YELLOW);
    _XL_PRINT(1, 1, "AMMO");
    _XL_SET_TEXT_COLOR(_XL_WHITE);
    _XL_PRINTD(5, 1, 2, ammo);

    /* invincibility indicator (row 1, right) */
    if (invinc_timer > 0) {
        _XL_SET_TEXT_COLOR(_XL_GREEN);
        _XL_PRINTD(XSize - 5, 1, 3, (uint16_t)(invinc_timer / 10));
    }
}

/* ═══════════ Update logic ═══════════ */

void update_drops(void)
{
    uint8_t i;
    uint8_t moved;

    for (i = 0; i < MAX_DROPS; i++) {
        if (!drops[i].active) continue;

        _XL_DELETE(drops[i].x, drops[i].y);
        if (drops[i].wide == 2) {
            _XL_DELETE((uint8_t)(drops[i].x + 1), drops[i].y);
        }

        moved = 0;
        /* drop falls every 2 frames at low difficulty,
           every frame at high difficulty */
        if (frame_counter % (uint8_t)(3 - (difficulty > 4 ? 2 : difficulty / 4)) == 0) {
            moved = 1;
        }

        if (moved) {
            drops[i].y++;
        }

        if (drops[i].y > YSize - 2) {
            drops[i].active = 0;
            score++;
        }
    }

    /* draw active drops */
    for (i = 0; i < MAX_DROPS; i++) {
        if (!drops[i].active) continue;
        if (drops[i].wide == 1) {
            _XL_DRAW(drops[i].x, drops[i].y, T_DROP, _XL_RED);
        } else {
            _XL_DRAW(drops[i].x, drops[i].y, T_WIDE_DROP, _XL_MAGENTA);
            _XL_DRAW((uint8_t)(drops[i].x + 1), drops[i].y, T_WIDE_DROP, _XL_MAGENTA);
        }
    }
}

void update_bullets(void)
{
    uint8_t i;
    uint8_t j;
    uint8_t hit;

    for (i = 0; i < MAX_BULLETS; i++) {
        if (!bullets[i].active) continue;

        _XL_DELETE(bullets[i].x, bullets[i].y);
        bullets[i].y--;

        if (bullets[i].y < 2) {
            bullets[i].active = 0;
            continue;
        }

        /* check if bullet hit a drop */
        hit = 0;
        for (j = 0; j < MAX_DROPS; j++) {
            if (!drops[j].active) continue;
            if (bullets[i].x == drops[j].x && bullets[i].y == drops[j].y) {
                hit = 1;
                break;
            }
            if (drops[j].wide == 2 && bullets[i].x == (uint8_t)(drops[j].x + 1)
                && bullets[i].y == drops[j].y) {
                hit = 1;
                break;
            }
        }

        if (hit) {
            /* destroy the drop */
            for (j = 0; j < MAX_DROPS; j++) {
                if (!drops[j].active) continue;
                if (bullets[i].x == drops[j].x && bullets[i].y == drops[j].y) {
                    _XL_DELETE(drops[j].x, drops[j].y);
                    if (drops[j].wide == 2)
                        _XL_DELETE((uint8_t)(drops[j].x + 1), drops[j].y);
                    drops[j].active = 0;
                }
            }
            score += DROP_SCORE;
            bullets[i].active = 0;
            _XL_TOCK_SOUND();
        } else {
            _XL_DRAW(bullets[i].x, bullets[i].y, T_BULLET, _XL_WHITE);
        }
    }
}

void update_items(void)
{
    uint8_t i;
    uint8_t collected;

    for (i = 0; i < MAX_ITEMS; i++) {
        if (!items[i].active) continue;

        _XL_DELETE(items[i].x, items[i].y);
        items[i].y++;

        if (items[i].y > YSize - 2) {
            items[i].active = 0;
            continue;
        }

        /* player collects item by moving onto it */
        collected = 0;
        if (items[i].x == player_x && items[i].y == PLAYER_Y) {
            collected = 1;
        }

        if (collected) {
            if (items[i].kind == 0) {
                score += BONUS_SCORE;
                _XL_PING_SOUND();
            } else {
                score += INVINC_SCORE;
                invinc_timer = INVINC_FRAMES;
                _XL_ZAP_SOUND();
            }
            items[i].active = 0;
        } else {
            if (items[i].kind == 0) {
                _XL_DRAW(items[i].x, items[i].y, T_BONUS, _XL_YELLOW);
            } else {
                _XL_DRAW(items[i].x, items[i].y, T_INVINC, _XL_GREEN);
            }
        }
    }
}

/* ═══════════ Collision ═══════════ */

uint8_t check_collision(void)
{
    uint8_t i;
    uint8_t hit;

    if (invinc_timer > 0) return 0;

    hit = 0;
    for (i = 0; i < MAX_DROPS; i++) {
        if (!drops[i].active) continue;
        if (drops[i].x == player_x && drops[i].y == PLAYER_Y) {
            hit = 1;
            break;
        }
        if (drops[i].wide == 2
            && (uint8_t)(drops[i].x + 1) == player_x
            && drops[i].y == PLAYER_Y) {
            hit = 1;
            break;
        }
    }
    return hit;
}

/* ═══════════ Title ═══════════ */

void show_title(void)
{
    _XL_CLEAR_SCREEN();
    _XL_SET_TEXT_COLOR(_XL_CYAN);
    _XL_PRINT(XSize / 2 - 3, 2, "DODGE");
    _XL_PRINT(XSize / 2 - 4, 3, "THE RAIN");
    _XL_SET_TEXT_COLOR(_XL_WHITE);
    _XL_PRINT(XSize / 2 - 8, 5, "MOVE LEFT RIGHT");
    _XL_PRINT(XSize / 2 - 8, 6, "FIRE TO SHOOT");
    _XL_PRINT(XSize / 2 - 8, 7, "COLLECT STARS");
    _XL_SET_TEXT_COLOR(_XL_YELLOW);
    _XL_PRINT(XSize / 2 - 5, 9, "PRESS ANY KEY");
    _XL_WAIT_FOR_INPUT();
}

/* ═══════════ Game Over ═══════════ */

void show_gameover(void)
{
    uint8_t i;

    for (i = 0; i < MAX_DROPS; i++) drops[i].active = 0;
    for (i = 0; i < MAX_BULLETS; i++) bullets[i].active = 0;
    for (i = 0; i < MAX_ITEMS; i++) items[i].active = 0;

    _XL_CLEAR_SCREEN();
    _XL_SET_TEXT_COLOR(_XL_RED);
    _XL_PRINT(4, 3, "GAME OVER");
    _XL_SET_TEXT_COLOR(_XL_WHITE);
    _XL_PRINT(4, 5, "SCORE");
    _XL_PRINTD(4, 6, 6, score);
    _XL_SET_TEXT_COLOR(_XL_CYAN);
    _XL_PRINT(4, 9, "PRESS ANY KEY");
    _XL_WAIT_FOR_INPUT();
}

/* ═══════════ Main ═══════════ */

int main(void)
{
    uint8_t  input;
    uint8_t  hit;
    uint16_t slowdown;
    uint8_t  interval;
    uint8_t  blink;

    _XL_INIT_GRAPHICS();
    _XL_INIT_INPUT();
    _XL_INIT_SOUND();

    while (1) {

        /* ── Title ── */
        show_title();

        /* ── Reset state ── */
        reset_drops();
        reset_bullets();
        reset_items();
        player_x     = (uint8_t)(XSize / 2);
        score        = 0;
        lives        = MAX_LIVES;
        ammo         = BULLET_START_AMMO;
        spawn_timer  = 0;
        item_timer   = 0;
        invinc_timer = 0;
        difficulty   = 1;
        frame_counter = 0;

        _XL_CLEAR_SCREEN();
        _XL_DRAW(player_x, PLAYER_Y, T_PLAYER, _XL_CYAN);
        draw_hud();

        slowdown = _XL_SLOW_DOWN_FACTOR;

        /* ── Playing loop ── */
        while (lives > 0) {

            /* difficulty ramp */
            frame_counter++;
            if (frame_counter == 0) {
                difficulty++;
                if (difficulty > 8) difficulty = 8;
                slowdown = (uint16_t)(_XL_SLOW_DOWN_FACTOR
                    / (uint16_t)(1 + (difficulty > 4 ? difficulty - 4 : 0)));
            }

            /* ── Spawn drops ── */
            spawn_timer++;
            interval = (uint8_t)(BASE_SPAWN + 2 - (difficulty > 6 ? 6 : difficulty / 2));
            if (interval < 2) interval = 2;
            if (spawn_timer >= interval) {
                spawn_drop();
                spawn_timer = 0;
            }

            /* ── Spawn items ── */
            item_timer++;
            if (item_timer >= ITEM_EVERY) {
                spawn_item();
                item_timer = 0;
            }

            /* ── Update drops ── */
            update_drops();

            /* ── Update bullets ── */
            update_bullets();

            /* ── Update items ── */
            update_items();

            /* ── Timing ── */
            _XL_SLOW_DOWN(slowdown);

            /* ── Invincibility countdown ── */
            if (invinc_timer > 0) {
                invinc_timer--;
                blink = (invinc_timer % 10 < 5) ? 1 : 0;
                if (blink) {
                    _XL_DELETE(player_x, PLAYER_Y);
                    _XL_DRAW(player_x, PLAYER_Y, T_INVINC, _XL_GREEN);
                } else {
                    _XL_DELETE(player_x, PLAYER_Y);
                    _XL_DRAW(player_x, PLAYER_Y, T_PLAYER, _XL_CYAN);
                }
            }

            /* ── Poll input and move ── */
            input = _XL_INPUT();

            if (_XL_LEFT(input) && player_x > XSize / 5) {
                _XL_DELETE(player_x, PLAYER_Y);
                player_x--;
                _XL_DRAW(player_x, PLAYER_Y, T_PLAYER, _XL_CYAN);
            }
            if (_XL_RIGHT(input) && player_x < XSize - 1 - XSize / 5) {
                _XL_DELETE(player_x, PLAYER_Y);
                player_x++;
                _XL_DRAW(player_x, PLAYER_Y, T_PLAYER, _XL_CYAN);
            }

            /* ── Fire ── */
            if (_XL_FIRE(input)) {
                fire_bullet();
            }

            /* ── Collision ── */
            hit = check_collision();
            if (hit) {
                lives--;
                _XL_EXPLOSION_SOUND();
                reset_drops();
                reset_bullets();
                reset_items();
                _XL_CLEAR_SCREEN();
                _XL_DRAW(player_x, PLAYER_Y, T_PLAYER, _XL_CYAN);
                draw_hud();
                _XL_SLEEP(1);
                if (lives > 0) {
                    _XL_WAIT_FOR_INPUT();
                }
            }

            /* ── Refresh HUD (score may have changed) ── */
            draw_hud();
        }

        /* ── Game over ── */
        show_gameover();
    }

    return 0;
}